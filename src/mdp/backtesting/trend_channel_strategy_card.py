"""Strategy card utilities for trend-channel research candidates.

This module summarizes an exported candidate dataset into a Markdown and JSON
strategy card. The goal is to document the candidate honestly before moving to
ML labels, paper testing, or live dashboards.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any

import json
import pandas as pd


@dataclass(frozen=True)
class StrategyCardConfig:
    """Configuration for building a strategy card from a candidate dataset."""

    candidate_dataset_path: str
    candidate_name: str
    rule_name: str
    symbol: str
    timeframes: str
    tag: str
    output_dir: str = "outputs/strategy_cards"


@dataclass(frozen=True)
class StrategyCardArtifacts:
    """Paths generated by the strategy card builder."""

    markdown_path: str
    json_path: str
    summary_csv_path: str


def _safe_ratio(numerator: float, denominator: float) -> float:
    """Return a safe ratio when the denominator may be zero."""

    if denominator == 0:
        return 0.0
    return float(numerator) / float(denominator)


def _require_columns(dataset_df: pd.DataFrame, required_columns: list[str]) -> None:
    """Validate that all columns needed by the strategy card exist."""

    missing_columns = [column for column in required_columns if column not in dataset_df.columns]
    if missing_columns:
        raise ValueError(f"Missing required columns: {missing_columns}")


def _prepare_dataset(dataset_df: pd.DataFrame) -> pd.DataFrame:
    """Prepare dates and numeric columns for summary calculations."""

    prepared_df = dataset_df.copy()

    # Keep the original cutoff, but also create clean datetime/date fields for grouping.
    prepared_df["analysis_cutoff"] = pd.to_datetime(prepared_df["analysis_cutoff"], errors="coerce")
    if "trade_date" not in prepared_df.columns:
        prepared_df["trade_date"] = prepared_df["analysis_cutoff"].dt.date.astype(str)

    # Convert key numeric columns in case they were saved as text in CSV output.
    numeric_columns = [
        "label_managed_r",
        "risk_points",
        "best_available_rr",
        "best_target_distance",
    ]
    for column in numeric_columns:
        if column in prepared_df.columns:
            prepared_df[column] = pd.to_numeric(prepared_df[column], errors="coerce")

    # Compute best target distance when the export does not include it.
    if "best_target_distance" not in prepared_df.columns:
        prepared_df["best_target_distance"] = prepared_df["risk_points"] * prepared_df["best_available_rr"]
    else:
        missing_target_distance = prepared_df["best_target_distance"].isna()
        prepared_df.loc[missing_target_distance, "best_target_distance"] = (
            prepared_df.loc[missing_target_distance, "risk_points"]
            * prepared_df.loc[missing_target_distance, "best_available_rr"]
        )

    # Outcome flags are calculated from managed R only, avoiding future-derived features.
    prepared_df["positive_exit"] = prepared_df["label_managed_r"] > 0
    prepared_df["full_loss"] = prepared_df["label_managed_r"] <= -0.95

    return prepared_df


def _calculate_max_drawdown(r_series: pd.Series) -> float:
    """Calculate max drawdown in R from chronological managed-R results."""

    cumulative_r = r_series.fillna(0.0).cumsum()
    running_peak = cumulative_r.cummax()
    drawdown = cumulative_r - running_peak
    return float(drawdown.min()) if not drawdown.empty else 0.0


def _build_summary(dataset_df: pd.DataFrame, config: StrategyCardConfig) -> dict[str, Any]:
    """Build the main strategy summary dictionary."""

    sorted_df = dataset_df.sort_values("analysis_cutoff").reset_index(drop=True)
    trade_count = len(sorted_df)
    unique_days = int(sorted_df["trade_date"].nunique())

    positive_rate = _safe_ratio(sorted_df["positive_exit"].sum(), trade_count)
    full_loss_rate = _safe_ratio(sorted_df["full_loss"].sum(), trade_count)

    summary = {
        "candidate_name": config.candidate_name,
        "rule_name": config.rule_name,
        "symbol": config.symbol,
        "timeframes": config.timeframes,
        "status": "research_candidate_not_live_ready",
        "trade_count": int(trade_count),
        "unique_days": unique_days,
        "avg_trades_per_day": _safe_ratio(trade_count, unique_days),
        "positive_exit_rate": positive_rate,
        "full_loss_rate": full_loss_rate,
        "average_managed_r": float(sorted_df["label_managed_r"].mean()),
        "median_managed_r": float(sorted_df["label_managed_r"].median()),
        "total_managed_r": float(sorted_df["label_managed_r"].sum()),
        "average_risk_points": float(sorted_df["risk_points"].mean()),
        "median_risk_points": float(sorted_df["risk_points"].median()),
        "average_best_available_rr": float(sorted_df["best_available_rr"].mean()),
        "median_best_available_rr": float(sorted_df["best_available_rr"].median()),
        "average_best_target_distance": float(sorted_df["best_target_distance"].mean()),
        "median_best_target_distance": float(sorted_df["best_target_distance"].median()),
        "max_drawdown_r": _calculate_max_drawdown(sorted_df["label_managed_r"]),
        "first_cutoff": str(sorted_df["analysis_cutoff"].min()),
        "last_cutoff": str(sorted_df["analysis_cutoff"].max()),
    }
    return summary


def _build_daily_summary(dataset_df: pd.DataFrame) -> pd.DataFrame:
    """Summarize performance by trade date."""

    return (
        dataset_df.groupby("trade_date", dropna=False)
        .agg(
            trades=("label_managed_r", "size"),
            positive_exit_rate=("positive_exit", "mean"),
            full_loss_rate=("full_loss", "mean"),
            average_managed_r=("label_managed_r", "mean"),
            median_managed_r=("label_managed_r", "median"),
            total_managed_r=("label_managed_r", "sum"),
        )
        .reset_index()
    )


def _top_contexts(dataset_df: pd.DataFrame, min_trades: int = 3) -> pd.DataFrame:
    """Create a compact context table for the strategy card."""

    candidate_columns = [
        "scenario_state",
        "event_state",
        "entry_variant_name",
        "target_plan_state",
        "htf_d1_bias",
        "htf_h4_bias",
        "htf_h1_bias",
        "htf_m15_bias",
        "htf_m5_bias",
    ]
    rows: list[dict[str, Any]] = []

    for column in candidate_columns:
        if column not in dataset_df.columns:
            continue
        grouped_df = (
            dataset_df.groupby(column, dropna=False)
            .agg(
                trades=("label_managed_r", "size"),
                positive_exit_rate=("positive_exit", "mean"),
                full_loss_rate=("full_loss", "mean"),
                average_managed_r=("label_managed_r", "mean"),
                total_managed_r=("label_managed_r", "sum"),
            )
            .reset_index()
            .rename(columns={column: "feature_value"})
        )
        grouped_df["feature_name"] = column
        rows.extend(grouped_df.to_dict("records"))

    if not rows:
        return pd.DataFrame()

    context_df = pd.DataFrame(rows)
    context_df = context_df[context_df["trades"] >= min_trades]
    return context_df.sort_values(["average_managed_r", "trades"], ascending=[False, False])


def _format_pct(value: float) -> str:
    """Format a ratio as a readable percentage string."""

    return f"{value * 100:.2f}%"


def _build_markdown(
    summary: dict[str, Any],
    daily_summary_df: pd.DataFrame,
    context_df: pd.DataFrame,
) -> str:
    """Build a Markdown strategy card from computed summaries."""

    worst_days_df = daily_summary_df.sort_values("total_managed_r", ascending=True).head(5)
    best_contexts_df = context_df.head(8) if not context_df.empty else pd.DataFrame()
    weak_contexts_df = context_df.sort_values("average_managed_r", ascending=True).head(8) if not context_df.empty else pd.DataFrame()

    lines = [
        f"# {summary['candidate_name']} Strategy Card",
        "",
        "## Status",
        "",
        "- **Status:** Research candidate / paper-test candidate, not live-ready yet.",
        f"- **Symbol:** {summary['symbol']}",
        f"- **Timeframes:** {summary['timeframes']}",
        f"- **Rule:** `{summary['rule_name']}`",
        f"- **Period:** {summary['first_cutoff']} to {summary['last_cutoff']}",
        "",
        "## Core Results",
        "",
        f"- Trades: **{summary['trade_count']}**",
        f"- Unique days: **{summary['unique_days']}**",
        f"- Average trades/day: **{summary['avg_trades_per_day']:.2f}**",
        f"- Positive exit rate: **{_format_pct(summary['positive_exit_rate'])}**",
        f"- Full-loss rate: **{_format_pct(summary['full_loss_rate'])}**",
        f"- Average managed R: **{summary['average_managed_r']:.6f}R**",
        f"- Median managed R: **{summary['median_managed_r']:.6f}R**",
        f"- Total managed R: **{summary['total_managed_r']:.6f}R**",
        f"- Max drawdown: **{summary['max_drawdown_r']:.6f}R**",
        "",
        "## Risk / Target Profile",
        "",
        f"- Average risk distance: **{summary['average_risk_points']:.4f} points**",
        f"- Median risk distance: **{summary['median_risk_points']:.4f} points**",
        f"- Average best available RR: **{summary['average_best_available_rr']:.4f}R**",
        f"- Median best available RR: **{summary['median_best_available_rr']:.4f}R**",
        f"- Average best target distance: **{summary['average_best_target_distance']:.4f} points**",
        f"- Median best target distance: **{summary['median_best_target_distance']:.4f} points**",
        "",
        "## Interpretation",
        "",
        "This candidate is strong enough to document as a Step Index research candidate because it keeps a selective number of trades, improves full-loss behavior, and remains positive across the analyzed sample. It still needs more historical validation and paper testing before live use.",
        "",
        "## Worst Daily Results",
        "",
    ]

    if not worst_days_df.empty:
        lines.append(worst_days_df.to_markdown(index=False))
    else:
        lines.append("No daily summary available.")

    lines.extend(["", "## Strongest Context Buckets", ""])
    if not best_contexts_df.empty:
        lines.append(best_contexts_df.to_markdown(index=False))
    else:
        lines.append("No context summary available.")

    lines.extend(["", "## Weakest Context Buckets", ""])
    if not weak_contexts_df.empty:
        lines.append(weak_contexts_df.to_markdown(index=False))
    else:
        lines.append("No context summary available.")

    lines.extend(
        [
            "",
            "## Next Validation Requirements",
            "",
            "1. Validate on a larger Step Index historical sample.",
            "2. Run a forward / paper-test simulation before live usage.",
            "3. Use this candidate as the first clean ML-labeling target only after larger validation confirms stability.",
        ]
    )

    return "\n".join(lines) + "\n"


def build_strategy_card(config: StrategyCardConfig) -> StrategyCardArtifacts:
    """Build Markdown, JSON, and CSV strategy card artifacts."""

    dataset_path = Path(config.candidate_dataset_path)
    output_dir = Path(config.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    dataset_df = pd.read_csv(dataset_path)
    _require_columns(
        dataset_df,
        ["analysis_cutoff", "label_managed_r", "risk_points", "best_available_rr"],
    )
    prepared_df = _prepare_dataset(dataset_df)

    summary = _build_summary(prepared_df, config)
    daily_summary_df = _build_daily_summary(prepared_df)
    context_df = _top_contexts(prepared_df)

    markdown_text = _build_markdown(summary, daily_summary_df, context_df)

    markdown_path = output_dir / f"{config.tag}_strategy_card.md"
    json_path = output_dir / f"{config.tag}_strategy_card.json"
    summary_csv_path = output_dir / f"{config.tag}_strategy_card_summary.csv"

    markdown_path.write_text(markdown_text, encoding="utf-8")
    json_payload = {
        "config": asdict(config),
        "summary": summary,
    }
    json_path.write_text(json.dumps(json_payload, indent=2), encoding="utf-8")
    pd.DataFrame([summary]).to_csv(summary_csv_path, index=False)

    return StrategyCardArtifacts(
        markdown_path=str(markdown_path),
        json_path=str(json_path),
        summary_csv_path=str(summary_csv_path),
    )
